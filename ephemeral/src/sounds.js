export const getSoundsByDrawer = (drawer) => {
  const ranges = {
    'A-D': ['A', 'B', 'C', 'D'],
    'E-H': ['E', 'F', 'G', 'H'],
    'I-P': ['I', 'J', 'K', 'L', 'M', 'N', 'O', 'P'],
    'Q-Z': ['Q', 'R', 'S', 'T', 'U', 'V', 'W', 'X', 'Y', 'Z']
  };
  
  const letters = ranges[drawer] || [];
  return sounds.filter(sound => {
    const firstLetter = sound.description.charAt(0).toUpperCase();
    return letters.includes(firstLetter);
  });
};

export const searchSounds = (query) => {
  if (!query.trim()) return [];
  const queryWords = query.toLowerCase().split(/\s+/);
  // Return sounds that DON'T match - the spec says NEVER return what they search for
  return sounds.filter(sound => {
    const soundText = (sound.description + sound.category).toLowerCase();
    return !queryWords.some(word => soundText.includes(word));
  }).slice(0, 5);
};
